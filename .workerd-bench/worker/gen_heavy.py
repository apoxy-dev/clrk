#!/usr/bin/env python3
# Generates worker-heavy.js: a non-trivial workerd bundle that exercises the
# three cost centers a real agent worker pays, so we can compare against the
# trivial echo floor:
#   - top-level PARSE: ~NFUNCS small functions collected into a dispatch table
#     (referenced, so V8 retains them; bodies are lazy-compiled on first call).
#   - top-level EVAL / module init: build a large Map, compile regexes, freeze a
#     config object -- the side-effect work real frameworks do at isolate start.
#   - per-request HANDLER work: dispatch through the table, hash a buffer with
#     Web Crypto SHA-256, and JSON.stringify a structured response.
# It is synthetic but representative; not a specific framework.
import sys

NFUNCS = int(sys.argv[1]) if len(sys.argv) > 1 else 12000
MAP_ENTRIES = int(sys.argv[2]) if len(sys.argv) > 2 else 20000
NREGEX = int(sys.argv[3]) if len(sys.argv) > 3 else 64
HASHES = int(sys.argv[4]) if len(sys.argv) > 4 else 10
DISPATCH = int(sys.argv[5]) if len(sys.argv) > 5 else 1500
HASHBUF = int(sys.argv[6]) if len(sys.argv) > 6 else 65536

out = []
w = out.append

w("// GENERATED by gen_heavy.py -- do not edit by hand.")
w("// Non-trivial workerd bundle: large parsed body + real top-level init +")
w("// per-request hashing/JSON, to contrast handler cost against the echo floor.")
w("")

# ---- NFUNCS small functions (parse cost) ----
for i in range(NFUNCS):
    p = 2654435761 ^ (i * 40503)
    w(f"function h{i}(x){{ const a=(x*{(i%97)+1}+{p & 0xffff})>>>0; return (a^(a>>>13)^{(i*2246822519)&0xffff})>>>0; }}")

w("")
w(f"const TABLE = [{','.join('h'+str(i) for i in range(NFUNCS))}];")
w("")

# ---- top-level init side effects (eval cost) ----
w(f"const LOOKUP = new Map();")
w(f"for (let i = 0; i < {MAP_ENTRIES}; i++) {{ LOOKUP.set('k'+i, (i*2654435761>>>0).toString(16)); }}")
w("const PATTERNS = [")
for i in range(NREGEX):
    w(f"  /^\\/api\\/v{i % 8}\\/(?<id>[a-f0-9]{{8}})\\/resource{i}$/,")
w("];")
w("const CONFIG = Object.freeze({ build: 'heavy', funcs: TABLE.length, routes: PATTERNS.length, entries: LOOKUP.size });")
w("const ENC = new TextEncoder();")
w("")

# ---- handler (per-request work) ----
w("""async function sha256(buf) {
  const d = await crypto.subtle.digest("SHA-256", buf);
  return new Uint8Array(d);
}

export default {
  async fetch(req) {
    // dispatch through a chunk of the table (lazy-compiles those bodies on the
    // first request, then runs warm).
    let acc = 0;
    for (let i = 0; i < DISPATCH_N && i < TABLE.length; i++) acc = (acc + TABLE[i](i ^ acc)) >>> 0;
    // a little routing/validation work against the precompiled patterns.
    const path = "/api/v3/deadbeef/resource7";
    let matched = -1;
    for (let i = 0; i < PATTERNS.length; i++) { if (PATTERNS[i].test(path)) { matched = i; break; } }
    // hash a real-sized buffer a few times (representative crypto / signing
    // work; 65536 bytes x HASH_N rounds).
    const buf = new Uint8Array(65536);
    const seed = (acc ^ (matched + 1)) >>> 0;
    for (let i = 0; i < buf.length; i++) buf[i] = (seed + i * 31) & 0xff;
    let h;
    for (let k = 0; k < HASH_N; k++) h = await sha256(buf);
    const body = JSON.stringify({
      ok: true, acc, matched, cfg: CONFIG,
      digest: Array.from(h.slice(0, 6)),
    });
    return new Response(body, { headers: { "content-type": "application/json" } });
  },
};
""".replace("DISPATCH_N", str(DISPATCH)).replace("HASH_N", str(HASHES)))

sys.stdout.write("\n".join(out))
